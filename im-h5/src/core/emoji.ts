/** 文本里是否只包含表情（用于气泡不换行的判断） */
export function isEmojiOnly(text: string): boolean {
  if (!text) return false;
  const stripped = text.replace(/[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}\u{200D}]/gu, '');
  return stripped.length === 0;
}
